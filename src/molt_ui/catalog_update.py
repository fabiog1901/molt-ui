"""Refresh the command catalog from the configured molt binary."""

from hashlib import sha256
import json
import logging
import os
from pathlib import Path
import re
from tempfile import NamedTemporaryFile

from .core.catalog import catalog_path, load_catalog
from .core.errors import MoltError
from .core.models import CatalogState, CommandCatalog, CommandSpec, OptionSpec
from .molt_process import MoltProcess
from .repo import Repo

logger = logging.getLogger(__name__)

COMMANDS = ("fetch", "verify", "convert postgres", "convert mysql", "convert oracle")


def parse_help(help_text: str) -> tuple[OptionSpec, ...]:
    options = []
    current = None
    for line in help_text.splitlines():
        match = re.match(r"^ {2,6}(?:-\w, )?--([\w-]+)\s+(.*)$", line)
        if match:
            name, tail = match.groups()
            if name == "help":
                current = None
                continue
            parts = re.split(r"\s{2,}", tail, maxsplit=1)
            kind = "string" if len(parts) == 2 else "bool"
            if kind == "string" and parts[0] == "int":
                kind = "int"
            # Cobra renders this boolean with a value placeholder.
            if name == "use-copy":
                kind = "bool"
            current = {"name": name, "kind": kind, "description": parts[-1]}
            options.append(current)
        elif current and line.startswith(" " * 20):
            current["description"] += " " + line.strip()
        else:
            current = None
    for option in options:
        defaults = [value for value in re.findall(r"\(default ([^)]+)\)", option["description"])
                    if value != "<unknown>"]
        value = defaults[0] if defaults else ""
        if value.startswith('"'):
            try:
                value = json.loads(value)
            except ValueError:
                value = value.strip('"')
        if option["kind"] == "bool":
            value = value == "true"
        elif option["kind"] == "int" and not value:
            value = "0"
        option["default"] = value
    return tuple(OptionSpec.model_validate(option) for option in options)


def generate_catalog(process: MoltProcess) -> CommandCatalog:
    commands = []
    for command in COMMANDS:
        arguments = tuple(command.split())
        result = process.run([*arguments, "--help"])
        if result.returncode:
            raise MoltError(result.stderr or result.stdout or f"Could not read help for {command}.")
        options = parse_help(result.stdout)
        if not options:
            raise ValueError(f"No options found in help for {command}.")
        commands.append(CommandSpec(id=command.replace(" ", "-"), arguments=arguments, options=options))
    return CommandCatalog(schema_version=1, commands=tuple(commands))



def write_catalog(catalog: CommandCatalog, output: Path) -> str:
    """Atomically replace the resource and return its content fingerprint."""
    content = (catalog.model_dump_json(indent=2, exclude_unset=True) + "\n").encode("utf-8")
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with NamedTemporaryFile(dir=output.parent, prefix=".command-catalog-", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
        os.replace(temporary, output)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    load_catalog.cache_clear()
    return sha256(content).hexdigest()


def refresh_catalog(process: MoltProcess, repo: Repo, *, output: Path | None = None) -> bool:
    """Refresh when the binary version or the recorded resource differs.

    A missing SQLite record also refreshes: the shipped resource may have been
    generated by a different binary. Only a successful write records a version.
    """
    result = process.run(["--version"])
    if result.returncode:
        raise MoltError(result.stderr.strip() or result.stdout.strip() or "molt --version failed.")
    version = result.stdout.strip() or result.stderr.strip()
    if not version:
        raise MoltError("molt --version returned no version.")
    output = catalog_path() if output is None else output
    state = repo.get_catalog_state()
    if state is not None and state.version == version:
        try:
            content = output.read_bytes()
            if state.sha256 == sha256(content).hexdigest():
                CommandCatalog.model_validate_json(content)
                return False
        except (OSError, ValueError):
            pass
    logger.info("Refreshing command catalog for %s", version)
    fingerprint = write_catalog(generate_catalog(process), output)
    repo.save_catalog_state(CatalogState(version=version, sha256=fingerprint))
    return True
